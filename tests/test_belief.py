import numpy as np
import pytest

from dream.agent.belief import Belief, NoiseModel, Prior, make_record
from dream.agent.model import FIXED, PRISMATIC, REVOLUTE, Hypotheses, predict_outcome
from dream.types import PartGeometry

GEO = PartGeometry(
    panel_center=np.array([0.0, 0.0, 0.6]),
    panel_half_extents=np.array([0.2, 0.01, 0.15]),
    handle_pos=np.array([0.1, -0.05, 0.62]),
)
# Signed axis directions: together they can move any prismatic or revolute joint.
PROBES = [np.array(d, float) for d in np.vstack([np.eye(3), -np.eye(3)])[[4, 0, 2, 1, 3, 5]]]


def _truth(kind):
    if kind == FIXED:
        axis, origin = [0, 0, 0], [0, 0, 0]
    elif kind == PRISMATIC:
        axis, origin = [0, -1, 0], [0, 0, 0]
    else:
        axis, origin = [0, 0, -1], [-0.2, -0.01, 0.6]
    return Hypotheses(
        kind=np.array([kind]),
        axis=np.array([axis], float),
        origin=np.array([origin], float),
        upper=np.array([0.25 if kind == PRISMATIC else 1.4]),
        friction=np.array([1.5]),
    )


def _simulate_records(truth, probes, rng, noise_std=(0.001, 0.0087), force=15.0):
    """Synthetic data generated by the agent's own model, plus Gaussian sensor noise."""
    handle = GEO.handle_pos.copy()
    records = []
    for d in probes:
        y, _, _ = predict_outcome(truth, GEO.handle_pos, handle, handle, d, np.array(0.06), force)
        y = y[0] + rng.normal(size=6) * np.repeat(noise_std, 3)
        records.append(make_record(handle, handle, d, 0.06, force, y[:3], y[3:]))
        handle = y[:3]
    return records


def test_prior_samples_lie_in_support():
    prior = Prior(GEO)
    rng = np.random.default_rng(0)
    for kind in (FIXED, PRISMATIC, REVOLUTE):
        h = prior.sample(kind, 500, rng)
        assert prior.in_support(h).all()
        if kind != FIXED:
            assert np.allclose(np.linalg.norm(h.axis, axis=1), 1)


def test_belief_starts_uniform_over_types():
    b = Belief(GEO, np.random.default_rng(0), n_particles=200)
    assert np.allclose(b.type_probs(), 1 / 3)
    assert b.type_entropy() == pytest.approx(np.log(3))


def test_noise_widens_with_predicted_motion_only():
    nm = NoiseModel()
    start = np.zeros((1, 6))
    still = np.zeros((1, 6))
    moved = np.array([[0.05, 0, 0, 0, 0, 0]])
    # Predicting no motion keeps the tight sensor-level width ...
    assert np.allclose(nm.sigma_for(still, start), nm.sigma)
    # ... so a "no motion" hypothesis is crushed by an observed 5 cm displacement.
    assert nm.loglik(still, moved, start)[0] < nm.loglik(moved, moved, start)[0] - 50
    # A hypothesis that predicts the motion tolerates a 15% error in its magnitude.
    near = moved * 1.15
    assert nm.loglik(near, moved, start)[0] > nm.loglik(moved, moved, start)[0] - 3


@pytest.mark.parametrize("kind", [FIXED, PRISMATIC, REVOLUTE])
def test_posterior_concentrates_on_true_type_with_synthetic_data(kind):
    rng = np.random.default_rng(kind)
    b = Belief(GEO, np.random.default_rng(10 + kind), n_particles=600)
    for rec in _simulate_records(_truth(kind), PROBES, rng):
        b.update(rec)
    assert b.map_type() == kind
    assert b.type_probs()[kind] > 0.9
    if kind != FIXED:
        est = b.estimate(kind)
        cos = float(np.dot(est["axis"], _truth(kind).axis[0]))
        assert np.degrees(np.arccos(np.clip(cos, -1, 1))) < 8


def test_revolute_pivot_recovered():
    rng = np.random.default_rng(5)
    b = Belief(GEO, np.random.default_rng(6), n_particles=800)
    for rec in _simulate_records(_truth(REVOLUTE), PROBES, rng):
        b.update(rec)
    origin = b.estimate(REVOLUTE)["origin"]
    # Distance between hinge lines (both vertical here) = horizontal offset of the foot points.
    assert np.linalg.norm((origin - np.array([-0.2, -0.01, 0.6]))[:2]) < 0.02


def test_no_motion_under_weak_force_is_weak_evidence_for_fixed():
    """A gentle push that does not move the part must not convince the agent it is fixed."""
    rng = np.random.default_rng(0)
    b = Belief(GEO, np.random.default_rng(1), n_particles=600)
    for rec in _simulate_records(_truth(FIXED), PROBES[:3], rng, force=0.5):
        b.update(rec)
    assert b.type_probs()[FIXED] < 0.6


def test_fit_check_separates_in_class_from_out_of_class_data():
    """Data with an unmodelled helical lift must fit worse than data from the model class."""
    rng = np.random.default_rng(3)
    truth = _truth(REVOLUTE)
    clean = _simulate_records(truth, PROBES, rng)
    lifted = []
    for rec in clean:
        q = np.linalg.norm(rec.y_obs[3:])  # hinge angle (rotation about a unit axis)
        y = rec.y_obs.copy()
        y[2] += 0.05 * q  # 5 cm of lift per radian, like a rising-butt hinge
        lifted.append(
            make_record(
                rec.handle_before,
                rec.ee_before,
                rec.direction,
                rec.distance,
                rec.max_force,
                y[:3],
                y[3:],
            )
        )
    fits = {}
    for name, records in (("clean", clean), ("lifted", lifted)):
        b = Belief(GEO, np.random.default_rng(4), n_particles=600)
        for rec in records:
            b.update(rec)
        fits[name] = b.fit_check()["chi2_per_dof"]
    assert fits["clean"] < 1.0
    assert fits["lifted"] > 2 * fits["clean"]


def test_geometric_prior_downweights_inward_opening_by_the_set_factor():
    rng = np.random.default_rng(0)
    uniform, soft = Prior(GEO), Prior(GEO, inward_weight=0.1)
    assert np.allclose(soft.front_normal(), [0, -1, 0])
    for kind in (PRISMATIC, REVOLUTE):
        f = uniform.opens_inward(uniform.sample(kind, 20000, rng)).mean()
        g = soft.opens_inward(soft.sample(kind, 20000, rng)).mean()
        expected = 0.1 * f / (0.1 * f + (1 - f))
        assert g == pytest.approx(expected, abs=0.02)
        assert soft.in_support(soft.sample(kind, 500, rng)).all()


def test_evidence_overturns_geometric_prior_for_an_inward_drawer():
    """A drawer that pushes *into* the cabinet is still identified despite the prior."""
    truth = _truth(PRISMATIC)
    truth.axis[:] = [0, 1, 0]
    rng = np.random.default_rng(2)
    b = Belief(GEO, np.random.default_rng(3), n_particles=600, prior=Prior(GEO, inward_weight=0.1))
    for rec in _simulate_records(truth, PROBES, rng):
        b.update(rec)
    assert b.map_type() == PRISMATIC and b.type_probs()[PRISMATIC] > 0.9
    assert np.dot(b.estimate(PRISMATIC)["axis"], [0, 1, 0]) > 0.98


def test_fit_check_never_alerts_before_minimum_evidence():
    """Validated rule (results/fresh_adequacy_validation): no inadequacy alert before probe 3."""
    rng = np.random.default_rng(0)
    b = Belief(GEO, np.random.default_rng(1), n_particles=200, adequacy_threshold=1e-12)
    records = _simulate_records(_truth(PRISMATIC), PROBES[:3], rng)
    for i, rec in enumerate(records, start=1):
        b.update(rec)
        assert b.fit_check()["model_adequate"] == (i < 3)


def test_reduced_likelihood_ignores_unobserved_rotation():
    """With observed_rotation=False (a camera on a round knob), the rotation entries of an
    observation have no influence, and chi2/dof counts only the 3 observed dimensions."""
    from dream.agent.belief import NoiseModel

    noise = NoiseModel(observed_rotation=False)
    y_pred = np.zeros((4, 6))
    y_start = np.zeros((4, 6))
    a = np.zeros(6)
    b = np.array([0, 0, 0, 1.0, -2.0, 0.5])  # wildly different rotations, same position
    assert np.allclose(noise.loglik(y_pred, a, y_start), noise.loglik(y_pred, b, y_start))
    full = NoiseModel()
    assert not np.allclose(full.loglik(y_pred, a, y_start), full.loglik(y_pred, b, y_start))
    c = np.array([0.01, 0, 0, 0, 0, 0])  # but position still counts
    assert np.all(noise.loglik(y_pred, c, y_start) < noise.loglik(y_pred, a, y_start))
    assert noise.dims == slice(0, 3) and full.dims == slice(0, 6)
